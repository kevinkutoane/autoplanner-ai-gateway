"""Pydantic models for outgoing AI gateway responses and errors."""

from typing import Optional
from pydantic import BaseModel, Field


class AIInvocationResponse(BaseModel):
    """Normalized response contract matching Flutter's CloudAIProvider expectation."""

    text: str = Field(..., description="The generated AI completion text or JSON string")
    promptTokens: int = Field(default=0, description="Tokens consumed by prompt/input")
    completionTokens: int = Field(default=0, description="Tokens generated by model")
    model: str = Field(..., description="Server-selected model name used for completion")


class ErrorDetail(BaseModel):
    """Structured details for gateway errors."""

    code: str = Field(..., description="Machine-readable error classification code")
    message: str = Field(..., description="Safe, client-facing descriptive message")
    requestId: Optional[str] = Field(default=None, description="Request trace correlation ID")


class ErrorResponse(BaseModel):
    """Canonical error envelope returned on all 4xx and 5xx responses."""

    error: ErrorDetail


class HealthResponse(BaseModel):
    """System status response for /health."""

    status: str = Field(default="healthy", description="Operational health status")
    version: str = Field(..., description="Current gateway release version")
    timestamp: str = Field(..., description="Current UTC ISO-8601 timestamp")
